# 苗字の読みのうち、普通の語や「名詞＋助詞」と読みが一致してしまうもの。
# SURNAME_SURFACES には入れる(苗字＋名前の判定には使う)が、DICTIONARY には
# 入れない。入れると候補0を奪って普通の文章が壊れる:
#     子が多い → 古賀多い     閣議を開き → 閣議を平木
#     木の下で → 木下で       地球は平らだ → 地球は平だ
SURNAME_NO_INJECT = {
    'こが', 'ひらき', 'きのした', 'たいら',
}


NAME_TABLE_COMMENT = """
// 「苗字の直後は名前」の判定に使う表。build_inline_dict.py が生成する。
//
// しげき/まこと/みなみ のような下の名前は、読みが一般語(刺激/誠/南)と
// 衝突するものが多い。単独で打ったときの既定を名前に寄せると普通の文章が
// 壊れるので、既定は動かさず「直前のセグメントが苗字として変換されている」
// ときだけ名前を引き上げる。間島刺激 → 間島茂樹。
"""
SURNAME_MARKER = 'const SURNAME_SURFACES: Record<string, string[]> = {\n'
GIVEN_MARKER = 'const GIVEN_NAME_SURFACES: Record<string, string[]> = {\n'

def _write_table(content: str, marker: str, table: dict, comment: str) -> str:
    lines = [f"  '{r}': [{', '.join(chr(39)+c+chr(39) for c in cs)}]," for r, cs in sorted(table.items())]
    block = comment + marker + "\n".join(lines) + "\n};\n"
    pos = content.find(marker)
    if pos != -1:
        start = pos
        if content[:pos].endswith(comment):
            start = pos - len(comment)
        close = content.find('\n};\n', pos)
        if close == -1:
            raise ValueError(marker + ' block not closed')
        return content[:start] + block + content[close + len('\n};\n'):]
    anchor = content.find('const VERB_CLASS:')
    if anchor == -1:
        raise ValueError('VERB_CLASS anchor not found')
    return content[:anchor] + block + '\n' + content[anchor:]

def write_name_tables(content: str) -> str:
    content = _write_table(content, SURNAME_MARKER, SURNAMES, NAME_TABLE_COMMENT)
    content = _write_table(content, GIVEN_MARKER, GIVEN_NAMES, '')
    return content

def load_existing(content: str) -> set:
    dict_start = content.find('const DICTIONARY:')
    brace_start = content.find('{', dict_start)
    rest = content[brace_start:]
    dict_block = content[brace_start:brace_start+re.search(r'\n\};', rest).start()+3]
    return set(m.group(1) for m in re.finditer(r"'([ぁ-んー]+)'\s*:", dict_block))

def patch(content: str, new_entries: dict) -> tuple:
    existing = load_existing(content)
    dict_start = content.find('const DICTIONARY:')
    brace_start = content.find('{', dict_start)
    rest = content[brace_start:]
    insert_pos = brace_start + re.search(r'\n\};', rest).start()

    lines = []
    for reading, cands in new_entries.items():
        if reading not in existing and re.match(r'^[ぁ-んー]+$', reading):
            cs = ', '.join(f"'{c}'" for c in cands)
            lines.append(f"  '{reading}': [{cs}],")
    if lines:
        content = content[:insert_pos] + '\n' + '\n'.join(lines) + content[insert_pos:]
    return content, len(lines)


def main():
    with open(ETS_FILE, 'r') as f:
        content = f.read()

    total = 0

    # 1. Verb conjugations
    verb_entries = {}
    for r_stem, k_stem, fn in VERBS:
        try:
            entries = fn(r_stem, k_stem)
            verb_entries.update(entries)
        except Exception as e:
            print(f"  warn: {r_stem}/{k_stem}: {e}")
    content, n = patch(content, verb_entries)
    total += n
    print(f"Verbs:     +{n} entries")

    # 1b. Verb POS/conjugation classes (track A Phase 1, see HANDOFF §6)
    verb_class = build_verb_class()
    content = write_verb_class(content, verb_class)
    print(f"VerbClass: {len(verb_class)} entries")

    # 2. Nouns
    content, n = patch(content, NOUNS)
    total += n
    print(f"Nouns:     +{n} entries")

    # 3. Places
    content, n = patch(content, PLACES)
    total += n
    print(f"Places:    +{n} entries")

    # 4. Surnames + given names
    injectable = {r: c for r, c in SURNAMES.items() if r not in SURNAME_NO_INJECT}
    content, n = patch(content, injectable)
    total += n
    # 下の名前は DICTIONARY に入れない。読みが一般語と衝突するものが多く
    # (かおり→香り、てつや→徹夜、ようこ→ようこと、ゆたか→豊か)、
    # 新規キーとして入れると候補0を奪って普通の文章が壊れる(実測11文)。
    # 代わりに GIVEN_NAME_SURFACES として出力し、lookup の末尾に足す形で
    # 到達可能にした上で、苗字の直後でだけ引き上げる。
    total += n
    print(f"Names:     +{n} entries (surnames only)")

    # 4b. 「苗字の直後は名前」用の実行時テーブル
    content = write_name_tables(content)
    print(f"NameTable: {len(SURNAMES)} surnames / {len(GIVEN_NAMES)} given names")

    with open(ETS_FILE, 'w') as f:
        f.write(content)
    print(f"Total new: +{total} entries")

if __name__ == '__main__':
    main()
